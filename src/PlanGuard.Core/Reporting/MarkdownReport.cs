using System.Globalization;
using System.Text;
using PlanGuard.Comparison;
using PlanGuard.Plans;
using PlanGuard.Snapshots;

namespace PlanGuard.Reporting;

/// <summary>
/// Renders a comparison as GitHub-flavoured Markdown for a pull-request comment and the job summary. The hidden
/// marker lets the commenter update its previous comment instead of adding a new one on every push.
/// </summary>
public static class MarkdownReport
{
    public const string Marker = "<!-- plan-guard:report -->";

    /// <summary>GitHub rejects comment bodies over 65,536 characters; plan details are dropped first to stay below it.</summary>
    public const int MaxLength = 60_000;

    public static string Render(ComparisonReport report)
    {
        ArgumentNullException.ThrowIfNull(report);
        var full = Build(report, includePlans: true);
        return full.Length <= MaxLength ? full : Build(report, includePlans: false);
    }

    private static string Build(ComparisonReport report, bool includePlans)
    {
        var sb = new StringBuilder();
        sb.AppendLine(Marker);
        sb.AppendLine(CultureInfo.InvariantCulture, $"## plan-guard: {Headline(report)}");
        sb.AppendLine();
        sb.AppendLine(CultureInfo.InvariantCulture,
            $"Compared **{report.Queries.Count}** queries: `{report.Baseline.Label}`{Sha(report.Baseline)} (baseline) vs `{report.Candidate.Label}`{Sha(report.Candidate)} (candidate), PostgreSQL {report.Candidate.ServerVersion}, median of {report.Candidate.Runs} runs.");
        sb.AppendLine();

        if (report.EnvironmentWarnings.Count > 0)
        {
            sb.AppendLine("> [!WARNING]");
            sb.AppendLine("> The two captures ran in different environments, so some differences may not come from this change:");
            foreach (var w in report.EnvironmentWarnings)
            {
                sb.AppendLine(CultureInfo.InvariantCulture, $"> - {w}");
            }

            sb.AppendLine();
        }

        sb.AppendLine("| Query | Verdict | Shared blocks | Temp blocks | Cost | Time (ms) | Plan |");
        sb.AppendLine("|---|---|---:|---:|---:|---:|---|");
        foreach (var q in report.Queries.OrderByDescending(q => q.Verdict).ThenBy(q => q.Id, StringComparer.Ordinal))
        {
            sb.AppendLine(CultureInfo.InvariantCulture,
                $"| `{Escape(q.Id)}` | {VerdictText(q.Verdict)} | {Pair(q.Baseline?.MedianSharedBlocks ?? q.Baseline?.SharedBlocksPerCall, q.Candidate?.MedianSharedBlocks ?? q.Candidate?.SharedBlocksPerCall)} | {Pair(q.Baseline?.MedianTempBlocks, q.Candidate?.MedianTempBlocks)} | {Pair(Cost(q.Baseline), Cost(q.Candidate))} | {Pair(q.Baseline?.MedianExecutionMs, q.Candidate?.MedianExecutionMs)} | {PlanCell(q)} |");
        }

        sb.AppendLine();
        foreach (var q in report.Queries.Where(q => q.Verdict is Verdict.Fail or Verdict.Warn or Verdict.Changed or Verdict.Improved)
                     .OrderByDescending(q => q.Verdict).ThenBy(q => q.Id, StringComparer.Ordinal))
        {
            AppendDetails(sb, q, includePlans);
        }

        sb.AppendLine("<sub>");
        var t = report.Thresholds;
        sb.AppendLine(CultureInfo.InvariantCulture,
            $"Thresholds: shared blocks x{t.BufferRatio} and +{t.BufferMinDelta} ({t.BufferGate}), temp blocks x{t.TempRatio} and +{t.TempMinDelta} ({t.TempGate}), cost x{t.CostRatio} and +{t.CostMinDelta} ({t.CostGate}), time x{t.TimeRatio} and +{t.TimeMinDeltaMs} ms ({t.TimeGate}). ");
        sb.AppendLine("Shared blocks = buffers hit + read, so a cold cache does not count as a regression. Generated by plan-guard.");
        sb.AppendLine("</sub>");
        if (!includePlans)
        {
            sb.AppendLine();
            sb.AppendLine("<sub>Plan trees were left out to fit GitHub's comment size limit; see the JSON report artifact.</sub>");
        }

        return sb.ToString();
    }

    private static void AppendDetails(StringBuilder sb, QueryComparison q, bool includePlans)
    {
        sb.AppendLine(CultureInfo.InvariantCulture, $"<details{(q.Verdict == Verdict.Fail ? " open" : string.Empty)}>");
        sb.AppendLine(CultureInfo.InvariantCulture, $"<summary><b>{Escape(q.Id)}</b>: {q.Verdict.ToString().ToUpperInvariant()}</summary>");
        sb.AppendLine();
        foreach (var f in q.Findings.OrderByDescending(f => f.Level))
        {
            sb.AppendLine(CultureInfo.InvariantCulture, $"- **{LevelText(f.Level)}** {f.Signal}: {f.Message}");
        }

        if (includePlans && q.Baseline is { Error: null } b && q.Candidate is { Error: null } c)
        {
            sb.AppendLine();
            if (q.PlanChanged)
            {
                sb.AppendLine("Baseline plan:");
                AppendCode(sb, PlanTreeRenderer.Render(b.Plan));
                sb.AppendLine("Candidate plan:");
                AppendCode(sb, PlanTreeRenderer.Render(c.Plan));
            }
            else
            {
                sb.AppendLine("Plan (unchanged):");
                AppendCode(sb, PlanTreeRenderer.Render(c.Plan));
            }
        }

        sb.AppendLine("</details>");
        sb.AppendLine();
    }

    private static void AppendCode(StringBuilder sb, string text)
    {
        // A fence longer than any backtick run in the content cannot be closed early by plan text.
        var fence = new string('`', Math.Max(3, LongestRun(text, '`') + 1));
        sb.AppendLine(fence + "text");
        sb.AppendLine(text);
        sb.AppendLine(fence);
    }

    private static int LongestRun(string s, char ch)
    {
        int best = 0, run = 0;
        foreach (var x in s)
        {
            run = x == ch ? run + 1 : 0;
            best = Math.Max(best, run);
        }

        return best;
    }

    internal static string Headline(ComparisonReport r)
    {
        var fail = r.Count(Verdict.Fail);
        var warn = r.Count(Verdict.Warn);
        var parts = new List<string>();
        if (fail > 0)
        {
            parts.Add($"{fail} regression{(fail == 1 ? string.Empty : "s")}");
        }

        if (warn > 0)
        {
            parts.Add($"{warn} warning{(warn == 1 ? string.Empty : "s")}");
        }

        var status = fail > 0 ? "FAILED" : warn > 0 ? "passed with warnings" : "passed";
        var improved = r.Count(Verdict.Improved);
        var changed = r.Count(Verdict.Changed);
        if (improved > 0)
        {
            parts.Add($"{improved} improved");
        }

        if (changed > 0)
        {
            parts.Add($"{changed} plan change{(changed == 1 ? string.Empty : "s")} within thresholds");
        }

        return parts.Count == 0 ? $"{status}, no plan or cost changes" : $"{status} ({string.Join(", ", parts)})";
    }

    internal static string VerdictText(Verdict v) => v switch
    {
        Verdict.Fail => "**FAIL**",
        Verdict.Warn => "warn",
        Verdict.Improved => "improved",
        Verdict.Changed => "plan changed",
        Verdict.New => "new",
        Verdict.Ignored => "ignored",
        _ => "pass",
    };

    private static string LevelText(FindingLevel l) => l switch
    {
        FindingLevel.Fail => "FAIL",
        FindingLevel.Warn => "warn",
        FindingLevel.Improvement => "better",
        _ => "info",
    };

    private static string PlanCell(QueryComparison q)
    {
        if (q.Candidate?.Error is not null)
        {
            return "error";
        }

        if (!q.PlanChanged)
        {
            return q.Baseline is null || q.Candidate is null ? "-" : "same";
        }

        if (q.Diff is { IsEmpty: false } d)
        {
            // Scans say the most about a regression (an index scan turning into a sequential scan), so they lead.
            var removed = d.Removed.FirstOrDefault(l => l.Contains("Scan", StringComparison.Ordinal)) ?? (d.Removed.Count > 0 ? d.Removed[0] : null);
            var added = d.Added.FirstOrDefault(l => l.Contains("Scan", StringComparison.Ordinal)) ?? (d.Added.Count > 0 ? d.Added[0] : null);
            return Escape($"{removed ?? "..."} -> {added ?? "..."}");
        }

        return "reordered";
    }

    private static double? Cost(QuerySnapshot? q) => q is null || q.Error is not null ? null : q.TotalCost;

    private static string Pair(double? b, double? c)
    {
        if (b is null && c is null)
        {
            return "-";
        }

        if (b is null || c is null)
        {
            return b is null ? $"- / {SnapshotComparer.Format(c!.Value)}" : $"{SnapshotComparer.Format(b.Value)} / -";
        }

        if (b.Value == c.Value)
        {
            return SnapshotComparer.Format(c.Value);
        }

        return $"{SnapshotComparer.Format(b.Value)} -> {SnapshotComparer.Format(c.Value)}";
    }

    private static string Sha(SnapshotMeta m) => m.GitSha is { Length: >= 7 } sha ? $" ({sha[..7]})" : string.Empty;

    /// <summary>Neutralises characters that would break a table cell or inject markup.</summary>
    internal static string Escape(string s) =>
        s.Replace("|", "\\|", StringComparison.Ordinal)
         .Replace("<", "&lt;", StringComparison.Ordinal)
         .Replace(">", "&gt;", StringComparison.Ordinal)
         .Replace("\r", " ", StringComparison.Ordinal)
         .Replace("\n", " ", StringComparison.Ordinal);
}
